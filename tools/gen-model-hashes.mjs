#!/usr/bin/env node
// Generate src/model-hashes.json — the committed SHA-256 manifest that
// model-integrity.js verifies downloaded weights against (H3).
//
// RUN THIS ON A TRUSTED HOST (clean machine, trusted network). It downloads every
// curated NER + Whisper STT model EXACTLY as the runtime does (same mirror →
// Hugging Face fallback via ensureLib), then hashes each model's on-disk .onnx (and
// .onnx.data) files. Commit the result. Re-run when the catalog changes or you bump
// a pinned dtype. Until it's populated, model-integrity.js is warn-and-allow (no
// protection), so this step is what switches fail-closed verification ON.
//
//   node tools/gen-model-hashes.mjs            # q8 (native default)
//   node tools/gen-model-hashes.mjs --dtype fp32
//
// NOTE: coverage = the dtype(s) you generate. A user who downloads a different dtype
// gets warn-and-allow for the files not in the manifest. Generate the dtypes you ship.

import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ensureLib, modelRoot } from '../src/ner-engine.js';
import { MODEL_CATALOG } from '../src/models.js';
import { STT_MODEL_CATALOG, sttModelEngine, sttModelDtype } from '../src/stt-models.js';

const OUT = fileURLToPath(new URL('../src/model-hashes.json', import.meta.url));
const dtypeArg = (() => { const i = process.argv.indexOf('--dtype'); return i > -1 ? process.argv[i + 1] : 'q8'; })();

function sha256(path) { return createHash('sha256').update(readFileSync(path)).digest('hex'); }

// Hash every weight file (.onnx + external-data .onnx.data) under a model's dir,
// keyed by path relative to that dir (matches what verifyModelWeights expects).
function hashModelDir(modelId) {
  const dir = join(modelRoot(), ...modelId.split('/'));
  if (!existsSync(dir)) { console.warn(`  ! ${modelId}: nothing on disk after download — skipped`); return null; }
  const files = readdirSync(dir, { recursive: true })
    .map((f) => String(f))
    .filter((f) => /\.onnx(\.data)?$/.test(f))
    .filter((f) => { try { return statSync(join(dir, f)).isFile(); } catch { return false; } });
  if (!files.length) { console.warn(`  ! ${modelId}: no .onnx files found — skipped`); return null; }
  const out = {};
  for (const f of files.sort()) out[f.split('\\').join('/')] = sha256(join(dir, f));
  console.log(`  ✓ ${modelId}: ${files.length} file(s)`);
  return out;
}

const lib = await ensureLib();
const manifest = {
  _README: 'SHA-256 hashes of curated model weight files, keyed by modelId then by path relative to the model cache dir. Generated by tools/gen-model-hashes.mjs on a trusted host — do NOT hand-edit.',
};

console.log(`Downloading + hashing NER models (dtype q8)…`);
for (const m of MODEL_CATALOG) {
  try {
    await lib.pipeline('token-classification', m.id, { dtype: 'q8' });
    const h = hashModelDir(m.id);
    if (h) manifest[m.id] = h;
  } catch (e) { console.warn(`  ! ${m.id}: ${e.message}`); }
}

console.log(`Downloading + hashing STT models (dtype ${dtypeArg})…`);
for (const m of STT_MODEL_CATALOG) {
  if (sttModelEngine(m.id) === 'parakeet-tdt') { console.warn(`  - ${m.id}: parakeet engine (not transformers.js) — hash separately, TODO`); continue; }
  try {
    await lib.pipeline('automatic-speech-recognition', m.id, { dtype: sttModelDtype(m.id) || dtypeArg });
    const h = hashModelDir(m.id);
    if (h) manifest[m.id] = h;
  } catch (e) { console.warn(`  ! ${m.id}: ${e.message}`); }
}

writeFileSync(OUT, JSON.stringify(manifest, null, 2) + '\n');
console.log(`\nWrote ${relative(process.cwd(), OUT)} — ${Object.keys(manifest).filter((k) => !k.startsWith('_')).length} models. Commit it to enable fail-closed verification.`);
